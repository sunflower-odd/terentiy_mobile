package ru.terentiy.mobile.core.poll

import java.time.Duration

/**
 * Частота опроса сервера.
 *
 * Реализованный контракт рекомендаций не даёт — в нём нет ни `poll_after_seconds`,
 * ни `Retry-After`. Значит интервалы выбирает клиент, и каждое число обязано
 * опираться на факт со стороны сервера, иначе через месяц оно станет магическим.
 */
object PollIntervals {

    /**
     * Агенты — раз в 10 секунд.
     *
     * Агент отправляет heartbeat каждые 10 секунд
     * (`terentiy_ai/agent/config/agent.example.toml`), а сервер считает его
     * недоступным через 30. Спрашивать чаще бессмысленно: новых данных не
     * появится. Ответ — сотни байт.
     */
    val Agents: Duration = Duration.ofSeconds(10)

    /**
     * События — раз в 30 секунд.
     *
     * От падения до появления в выдаче проходит около 15 секунд пост-ролла
     * (`clips.after_seconds`) плюс запись и загрузка клипа агентом. Спрашивать
     * чаще нечего, а выдача тяжёлая: пагинации нет, и вместе с каждым событием
     * приходит его ML-диагностика.
     */
    val Events: Duration = Duration.ofSeconds(30)

    /** Потолок при отступе: дальше растягивать паузу бессмысленно. */
    val MaxBackoff: Duration = Duration.ofMinutes(5)
}
