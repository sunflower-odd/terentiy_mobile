package ru.terentiy.mobile.data.local

import ru.terentiy.mobile.domain.Session

/**
 * Хранилище значений, которые не должны лежать на диске открытым текстом:
 * идентификатор устройства и токен сессии.
 */
interface SecureStorage {

    /**
     * Идентификатор этого устройства для сервера.
     *
     * Создаётся при первом обращении и дальше не меняется. Это случайный UUID,
     * а не ANDROID_ID: идентификатор устройства — персональные данные, и
     * отправлять его ради технического ключа незачем.
     * См. docs/adr/0004-proiskhozhdenie-device-id.md.
     */
    fun deviceId(): String

    /**
     * Выдаёт новый идентификатор устройства и стирает сессию.
     *
     * Нужен ровно для одного случая — пользователь забыл PIN. Сброса PIN на
     * сервере нет, повторная активация того же устройства отклоняется, поэтому
     * единственный путь назад — представиться новым устройством.
     */
    fun rotateDeviceId(): String

    fun session(): Session?

    fun saveSession(session: Session)

    fun clearSession()
}
